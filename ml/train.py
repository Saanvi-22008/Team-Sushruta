"""Train and evaluate the trend-watch model, then export it as plain JSON.

Run from the repo root:
    pip install -r ml/requirements.txt
    python -m ml.generate_data
    python -m ml.train

Choices and why:
- Logistic regression: small, fast, and every weight can be read and explained.
- The split is by WOUND (not by row), so no wound appears in both train and test.
- The model is compared with a naive baseline ("is pH already above 7.3?") so
  we can see whether it adds anything.
- Weights are exported to JSON so the API needs no scikit-learn at run time.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import average_precision_score, precision_score, recall_score, roc_auc_score
from sklearn.model_selection import GroupShuffleSplit
from sklearn.preprocessing import StandardScaler

from ml.features import FEATURE_NAMES, HORIZON, WINDOW, extract


def load(path: Path) -> tuple[np.ndarray, np.ndarray, np.ndarray, np.ndarray]:
    X, y, groups, ph_last = [], [], [], []
    with path.open(encoding="utf-8") as handle:
        for line in handle:
            item = json.loads(line)
            features = extract(item["window"])
            X.append(features)
            y.append(item["y"])
            groups.append(item["wound"])
            ph_last.append(features[0])
    return np.array(X), np.array(y), np.array(groups), np.array(ph_last)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--data", default="ml/data/synthetic.jsonl")
    parser.add_argument("--model-out", default="ml/model.json")
    parser.add_argument("--metrics-out", default="ml/metrics.json")
    parser.add_argument("--threshold", type=float, default=0.5)
    args = parser.parse_args()

    X, y, groups, ph_last = load(Path(args.data))
    split = GroupShuffleSplit(n_splits=1, test_size=0.25, random_state=7)
    train, test = next(split.split(X, y, groups))

    scaler = StandardScaler().fit(X[train])
    model = LogisticRegression(max_iter=1000, class_weight="balanced")
    model.fit(scaler.transform(X[train]), y[train])
    prob = model.predict_proba(scaler.transform(X[test]))[:, 1]
    pred = (prob >= args.threshold).astype(int)

    baseline_pred = (ph_last[test] > 7.3).astype(int)
    metrics = {
        "rows_train": int(len(train)), "rows_test": int(len(test)),
        "wounds_test": int(len(set(groups[test]))),
        "positive_rate_test": round(float(y[test].mean()), 3),
        "roc_auc": round(float(roc_auc_score(y[test], prob)), 3),
        "average_precision": round(float(average_precision_score(y[test], prob)), 3),
        "precision": round(float(precision_score(y[test], pred, zero_division=0)), 3),
        "recall": round(float(recall_score(y[test], pred, zero_division=0)), 3),
        "baseline_ph_above_7_3": {
            "precision": round(float(precision_score(y[test], baseline_pred, zero_division=0)), 3),
            "recall": round(float(recall_score(y[test], baseline_pred, zero_division=0)), 3),
        },
        "operating_points": [
            {
                "threshold": t,
                "precision": round(float(precision_score(y[test], (prob >= t).astype(int), zero_division=0)), 3),
                "recall": round(float(recall_score(y[test], (prob >= t).astype(int), zero_division=0)), 3),
            }
            for t in (0.3, 0.5, 0.7, 0.85, 0.95)
        ],
        "data": "synthetic (generated by ml/generate_data.py). Results show the pipeline works, not clinical accuracy.",
    }

    artifact = {
        "type": "logistic_regression",
        "window": WINDOW, "horizon": HORIZON, "threshold": args.threshold,
        "features": FEATURE_NAMES,
        "mean": scaler.mean_.tolist(), "scale": scaler.scale_.tolist(),
        "coef": model.coef_[0].tolist(), "intercept": float(model.intercept_[0]),
        "trained_on": "synthetic", "metrics": metrics,
    }
    Path(args.model_out).write_text(json.dumps(artifact, indent=2), encoding="utf-8")
    Path(args.metrics_out).write_text(json.dumps(metrics, indent=2), encoding="utf-8")
    print(json.dumps(metrics, indent=2))
    ranked = sorted(zip(FEATURE_NAMES, model.coef_[0]), key=lambda p: -abs(p[1]))
    print("strongest features:", [(n, round(float(c), 2)) for n, c in ranked[:4]])


if __name__ == "__main__":
    main()
